/**
 * Estrae un nome completo dalla categoria nella lingua scelta.
 * length: 1 indica un elemento del dizionario, anche se contiene spazi.
 * I nomi sono suggerimenti: estrazioni successive possono ripetersi.
 */
export function generateName(category: NameCategory, language: NameLanguage = "it"): string {
  return uniqueNamesGenerator({
    dictionaries: [nameDictionaries[language][category]],
    length: 1,
    separator: " ",
    style: "capital",
  });
}
