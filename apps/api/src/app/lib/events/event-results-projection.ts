import type {
  PlannedEventResponse,
  PlannedTableResponse,
  TableRecord,
} from "@board-game-organizer/schemas";

/** Allowlist, not a spread: this audience never inherits Group metadata or planning data. */
export function sharedEventResults(
  event: PlannedEventResponse,
  tables: readonly TableRecord[],
): PlannedEventResponse {
  const finished = tables.filter((table) => table.confirmed && table.results);
  return {
    id: event.id,
    name: event.name,
    adminUserId: event.adminUserId,
    groupId: null,
    groupName: null,
    groupType: null,
    visibility: "PRIVATE",
    shareResultsWithFriends: true,
    timeZone: event.timeZone,
    startTime: event.startTime,
    endsAt: event.endsAt,
    dates: event.dates.filter((date) => date.id === event.confirmed?.dateId),
    locations: event.locations.filter((location) => location.id === event.confirmed?.locationId),
    confirmed: event.confirmed,
    status: event.status,
    version: event.version,
    planningGeneration: event.planningGeneration,
    createdAt: event.createdAt,
    updatedAt: event.updatedAt,
    role: "viewer",
    readOnly: true,
    sharedResultsOnly: true,
    canManage: false,
    canEdit: false,
    canInvite: false,
    canRegister: false,
    canVote: false,
    canConfirm: false,
    canReplan: false,
    canFinalize: false,
    canProposeDates: false,
    canProposeLocations: false,
    myRegistrations: [],
    myDemonstrator: false,
    tableCount: finished.length,
    participantCount: new Set(finished.flatMap((table) => table.confirmed!.playerIds)).size,
  };
}

export function sharedTableResults(table: PlannedTableResponse): PlannedTableResponse {
  return {
    id: table.id,
    eventId: table.eventId,
    name: table.name,
    order: table.order,
    minPlayers: table.minPlayers,
    maxPlayers: table.maxPlayers,
    games: table.games.filter((game) => game.gameId === table.confirmed?.gameId),
    gamesDetail: table.gamesDetail.filter((game) => game.id === table.confirmed?.gameId),
    rankingEnabled: table.rankingEnabled,
    confirmed: table.confirmed,
    results: table.results,
    createdAt: table.createdAt,
    updatedAt: table.updatedAt,
    eventName: table.eventName,
    eventVersion: table.eventVersion,
    eventSchedule: table.eventSchedule
      ? {
          localStartsAt: table.eventSchedule.localStartsAt,
          location: table.eventSchedule.location,
          dateCount: 1,
          locationCount: 1,
        }
      : undefined,
    eventStatus: table.eventStatus,
    adminUserId: table.adminUserId,
    groupId: null,
    groupName: null,
    groupType: null,
    readOnly: true,
    sharedResultsOnly: true,
    canManage: false,
    canProposeGames: false,
    canRegister: false,
    canRespond: false,
    canLeave: false,
    canInvite: false,
    myRegistration: null,
    myPosition: null,
    acceptedCount: table.confirmed?.playerIds.length ?? 0,
    seatedCount: table.confirmed?.playerIds.length ?? 0,
    pendingRegistrationCount: 0,
    pendingCount: 0,
    waitingCount: 0,
    ratingChanges: table.ratingChanges,
    winners: table.winners,
    resultProfiles: table.resultProfiles?.map((profile) => ({
      userId: profile.userId,
      name: profile.name,
      username: profile.username,
      avatarUrl: profile.avatarUrl,
      email: null,
    })),
  };
}
